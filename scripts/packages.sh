#!/bin/sh
# Writes the Homebrew formula and the Scoop manifest for a release, using the
# SHA-256 sums from that release's checksums.txt. The release workflow runs
# this after publishing and commits the result to main.
# Usage: packages.sh 0.1.0 dist/checksums.txt [repo-root]
set -eu
version=${1#v}
sums=$2
root=${3:-.}
repo=MaiSamayTha/leftover
base="https://github.com/$repo/releases/download/v$version"

sum() {
  s=$(awk -v f="$1" '$2 == f || $2 == "*"f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "packages: $1 isn't in $sums" >&2; exit 1; }
  echo "$s"
}

mkdir -p "$root/Formula" "$root/bucket"

cat > "$root/Formula/leftover.rb" <<RUBY
# Generated by scripts/packages.sh for each release. Install with:
#   brew tap maisamaytha/leftover https://github.com/$repo
#   brew install maisamaytha/leftover/leftover
class Leftover < Formula
  desc "Explains the space your dev tools leave behind and clears it safely"
  homepage "https://maisamaytha.github.io/leftover/"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/leftover-macos-arm64.tar.gz"
      sha256 "$(sum leftover-macos-arm64.tar.gz)"
    end
    on_intel do
      url "$base/leftover-macos-amd64.tar.gz"
      sha256 "$(sum leftover-macos-amd64.tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$base/leftover-linux-arm64.tar.gz"
      sha256 "$(sum leftover-linux-arm64.tar.gz)"
    end
    on_intel do
      url "$base/leftover-linux-amd64.tar.gz"
      sha256 "$(sum leftover-linux-amd64.tar.gz)"
    end
  end

  def install
    bin.install "leftover"
    generate_completions_from_executable(bin/"leftover", "completion", shells: [:bash, :zsh, :fish])
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/leftover --version")
  end
end
RUBY

cat > "$root/bucket/leftover.json" <<JSON
{
    "version": "$version",
    "description": "Explains the space your dev tools leave behind and clears it safely.",
    "homepage": "https://maisamaytha.github.io/leftover/",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "$base/leftover-windows-amd64.zip",
            "hash": "$(sum leftover-windows-amd64.zip)"
        },
        "arm64": {
            "url": "$base/leftover-windows-arm64.zip",
            "hash": "$(sum leftover-windows-arm64.zip)"
        }
    },
    "bin": "leftover.exe",
    "shortcuts": [["leftover.exe", "Leftover"]],
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": { "url": "https://github.com/$repo/releases/download/v\$version/leftover-windows-amd64.zip" },
            "arm64": { "url": "https://github.com/$repo/releases/download/v\$version/leftover-windows-arm64.zip" }
        },
        "hash": { "url": "\$baseurl/checksums.txt" }
    }
}
JSON
echo "packages: wrote Formula/leftover.rb and bucket/leftover.json for $version"
